# ========================================
# 【重要】責任ある利用のためのホワイトリスト
# ========================================
# 自分のチャンネルの URL をここに列挙してください。
# このリストに含まれるチャンネルの動画のみダウンロード可能です。
#
# 例:
#   $OwnChannelUrls = @(
#       "https://www.youtube.com/@YourChannel",
#       "https://www.youtube.com/channel/UCxxxxxxxxxxxx"
#   )
#
# 空のまま = どの動画もダウンロード不可（最も安全）
# ========================================
$OwnChannelUrls = @(
    # ここに自分のチャンネル URL を追加
)

# ========================================
# オプトイン: 上記以外のソースも許可するか
# ========================================
# $true にすると、上記ホワイトリスト以外の URL も受け付けます。
#
# ★ 変更前に必ず確認してください:
#   - ダウンロード対象の著作権を保有しているか
#   - 権利者から明示的な許可を得ているか
#   - 自由にダウンロード可能なライセンスか
#   - 居住国の法律で許可されているか
# ========================================
$AllowNonOwnedContent = $false   # ★ デフォルト: $false（自分の動画のみ）

# ========================================
# その他の設定
# ========================================
$NavidromeMusicPath = ""   # 空なら自動検出（$env:USERPROFILE\Downloads\navidrome*\music）